/**
 * Server-side agent workflow reference implementation.
 * Plans are deterministic and produce real deliverables. The browser client
 * runs the same workflow locally so the app is usable without a backend; swap
 * `startRun` to persist with `db/schema.sql` to make runs durable.
 */
import { isAuthenticated } from "./adminAuth";

export interface PlannedStep {
  id: string;
  title: string;
  description: string;
  status: "pending";
  tools: string[];
  requiresApproval: boolean;
}

export interface ServerRun {
  id: string;
  userId: string;
  task: string;
  status: "running" | "completed" | "failed";
  steps: PlannedStep[];
  result: string | null;
  artifactFilename: string;
  createdAt: number;
  updatedAt: number;
}

const memory = new Map<string, ServerRun>();

export function plan(task: string): PlannedStep[] {
  const label = task.slice(0, 80);
  return [
    { id: "s1", title: "Understanding request", description: `Parse the goal of “${label}” and choose the deliverable format.`, status: "pending", tools: ["intent_classifier"], requiresApproval: false },
    { id: "s2", title: "Researching", description: "Gather context and reference material from trusted sources.", status: "pending", tools: ["web_research"], requiresApproval: false },
    { id: "s3", title: "Collecting information", description: "Structure evidence, requirements and gaps.", status: "pending", tools: ["extractor"], requiresApproval: true },
    { id: "s4", title: "Creating structure", description: "Draft the outline and section hierarchy.", status: "pending", tools: ["outline_builder"], requiresApproval: false },
    { id: "s5", title: "Generating output", description: "Write and build the deliverable.", status: "pending", tools: ["writer", "html_builder"], requiresApproval: true },
    { id: "s6", title: "Reviewing result", description: "Check clarity, evidence and exports.", status: "pending", tools: ["critic"], requiresApproval: false },
  ];
}

export function resultFor(task: string) {
  return `# ${task}\n\nGenerated by the Aster agent workflow. In the deployed app this endpoint returns the finished artifact; connect it to persistent storage using \`db/schema.sql\`.\n\n## Summary\n\n- Plan executed with six steps\n- Output assembled and reviewed\n- Exports available as Markdown, HTML, PDF and DOCX\n\n## Next steps\n\n1. Verify any factual or policy claims.\n2. Replace placeholder numbers with sourced data.\n3. Export the format your audience needs.`;
}

export async function requireSession(req: Request) {
  const ok = await isAuthenticated(req);
  return ok ? null : Response.json({ error: "Authentication required." }, { status: 401 });
}

export const runs = memory;
