import type { Artifact } from "./types";

export function downloadBlob(filename: string, blob: Blob) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 4000);
}

export function downloadText(filename: string, content: string, mime = "text/plain") {
  downloadBlob(filename, new Blob([content], { type: `${mime};charset=utf-8` }));
}

function plain(artifact: Artifact) {
  if (artifact.kind === "html") {
    return artifact.content
      .replace(/<style[\s\S]*?<\/style>/gi, "")
      .replace(/<script[\s\S]*?<\/script>/gi, "")
      .replace(/<\/(p|div|h[1-6]|li|tr)>/gi, "\n")
      .replace(/<[^>]+>/g, " ")
      .replace(/&nbsp;/g, " ")
      .replace(/&amp;/g, "&")
      .replace(/[ \t]+/g, " ")
      .replace(/\n{3,}/g, "\n\n")
      .trim();
  }
  return artifact.content;
}

export function downloadMarkdown(artifact: Artifact) {
  const name = artifact.filename.replace(/\.[^.]+$/, "") + ".md";
  const body = artifact.kind === "markdown" ? artifact.content : `# ${artifact.title}\n\n\`\`\`html\n${artifact.content}\n\`\`\`\n`;
  downloadText(name, body, "text/markdown");
}

export function downloadHtml(artifact: Artifact) {
  const html =
    artifact.kind === "html"
      ? artifact.content
      : `<!doctype html><html><head><meta charset="utf-8"><title>${escapeHtml(artifact.title)}</title>
<style>body{font-family:-apple-system,Segoe UI,Inter,sans-serif;max-width:760px;margin:56px auto;padding:0 24px;line-height:1.7;color:#1a1a1f}h1,h2,h3{letter-spacing:-.02em}pre{background:#f4f4f2;padding:16px;border-radius:12px;overflow:auto}code{font-family:ui-monospace,Menlo,monospace}</style></head>
<body><pre style="background:none;padding:0;white-space:pre-wrap">${escapeHtml(plain(artifact))}</pre></body></html>`;
  downloadText(artifact.filename.replace(/\.[^.]+$/, "") + ".html", html, "text/html");
}

export async function downloadPdf(artifact: Artifact) {
  const { jsPDF } = await import("jspdf");
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const width = doc.internal.pageSize.getWidth();
  const height = doc.internal.pageSize.getHeight();
  const margin = 56;
  const maxWidth = width - margin * 2;
  let y = margin;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text(artifact.title, margin, y, { maxWidth });
  y += 30;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10.5);

  const lines = plain(artifact)
    .split("\n")
    .flatMap((line) => doc.splitTextToSize(line.replace(/^#{1,6}\s*/, "").replace(/\*\*/g, ""), maxWidth) as string[]);

  for (const line of lines) {
    if (y > height - margin) {
      doc.addPage();
      y = margin;
    }
    doc.text(line || " ", margin, y);
    y += 15;
  }
  doc.save(artifact.filename.replace(/\.[^.]+$/, "") + ".pdf");
}

export async function downloadDocx(artifact: Artifact) {
  const { Document, Packer, Paragraph, TextRun, HeadingLevel } = await import("docx");
  const children: InstanceType<typeof Paragraph>[] = [
    new Paragraph({ text: artifact.title, heading: HeadingLevel.TITLE }),
    new Paragraph({ children: [new TextRun({ text: "Generated by Aster Agent", italics: true, size: 18, color: "888888" })] }),
  ];

  for (const raw of plain(artifact).split("\n")) {
    const h = raw.match(/^(#{1,3})\s+(.*)$/);
    if (h) {
      children.push(
        new Paragraph({
          text: h[2].replace(/\*\*/g, ""),
          heading: h[1].length === 1 ? HeadingLevel.HEADING_1 : h[1].length === 2 ? HeadingLevel.HEADING_2 : HeadingLevel.HEADING_3,
          spacing: { before: 240, after: 100 },
        }),
      );
      continue;
    }
    if (!raw.trim()) {
      children.push(new Paragraph({ text: "" }));
      continue;
    }
    const isBullet = /^[-*]\s+/.test(raw);
    children.push(
      new Paragraph({
        text: raw.replace(/^[-*]\s+/, "").replace(/^\d+\.\s+/, "").replace(/\*\*/g, "").replace(/`/g, ""),
        bullet: isBullet ? { level: 0 } : undefined,
        spacing: { after: 60 },
      }),
    );
  }

  const document = new Document({ sections: [{ children }] });
  const blob = await Packer.toBlob(document);
  downloadBlob(artifact.filename.replace(/\.[^.]+$/, "") + ".docx", blob);
}

function escapeHtml(s: string) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}
